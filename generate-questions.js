function generateQuestions() {
  const questions = [];
  let id = 1;

  for (let i = 0; i < 1000; i++) {
    const type = i % 3 === 2 ? 'judgment' : 'single';
    const pool = type === 'single' ? questionTemplates.single : questionTemplates.judgment;
    const template = pool[i % pool.length];

    const q = {
      id: id++,
      type: type,
      question: template.q,
      options: [...template.o],
      answer: template.a,
      category: template.cat
    };

    questions.push(q);
  }

  return questions;
}

